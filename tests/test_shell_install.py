"""install.sh against a throwaway HOME.

Fast tests use AIRLINX_PYTHON (no venv, no pip) and AIRLINX_SKIP_DEPS=1. One slow test builds the real own venv.
The uninstall tests plant unrelated files and check that nothing outside AirLinx's own paths is touched.
"""
import hashlib
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
APP_ID = "io.github.airlinx"

pytestmark = pytest.mark.skipif(shutil.which("bash") is None, reason="bash required")


def _env(home, **extra):
    env = {k: v for k, v in os.environ.items()
           if not k.startswith(("XDG_", "AIRLINX_", "VIRTUAL_ENV", "PYTHONPATH"))}
    env.update(HOME=str(home), AIRLINX_SKIP_DEPS="1", **extra)
    return env


def run(home, *args, **extra):
    return subprocess.run(["bash", str(ROOT / "install.sh"), *args], env=_env(home, **extra), capture_output=True,
                          text=True, timeout=120)


def install(home, *args, **extra):
    extra.setdefault("AIRLINX_PYTHON", sys.executable)
    return run(home, *args, **extra)


# regenerated by gtk-update-icon-cache / update-desktop-database / uv, not by AirLinx
TOOL_CACHES = {"mimeinfo.cache", "icon-theme.cache"}


def files(root: Path):
    """{relative path: sha1 or symlink target} for every file and symlink below root (tool caches ignored)."""
    out = {}
    for p in sorted(root.rglob("*")):
        if p.name in TOOL_CACHES or ".cache" in p.relative_to(root).parts[:1]:
            continue
        if p.is_symlink():
            out[str(p.relative_to(root))] = "->" + os.readlink(p)
        elif p.is_file():
            out[str(p.relative_to(root))] = hashlib.sha1(p.read_bytes()).hexdigest()
    return out


@pytest.fixture
def home(tmp_path):
    h = tmp_path / "home"
    h.mkdir()
    return h


