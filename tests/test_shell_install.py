@pytest.mark.slow
def test_builds_own_venv_with_system_site_packages_and_uninstalls(home, tmp_path):
    if not Path("/usr/bin/python3").exists():
        pytest.skip("needs /usr/bin/python3")
    r = run(home, "--autostart")                                # no AIRLINX_PYTHON: install.sh creates its own venv
    assert r.returncode == 0, r.stderr
    prefix = home / ".local/share/airlinx"
    venv_py = prefix / "venv/bin/python"
    assert venv_py.exists()
    assert "include-system-site-packages = true" in (prefix / "venv/pyvenv.cfg").read_text()
    assert str(venv_py) in (home / ".local/bin/airlinx").read_text()
    assert (home / ".config/autostart" / f"{APP_ID}.desktop").exists()
    assert run(home, "--uninstall").returncode == 0
    assert not prefix.exists() and files(home) == {}
