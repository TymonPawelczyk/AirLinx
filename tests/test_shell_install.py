def exec_argv(path):
    """Every Exec= of a .desktop file as the argv GLib builds from it (key-file unescape, then shell-style split)."""
    GLib = pytest.importorskip("gi.repository.GLib")

    kf = GLib.KeyFile()
    kf.load_from_file(str(path), GLib.KeyFileFlags.NONE)
    out = []
    for group in kf.get_groups()[0]:
        value = kf.get_string(group, "Exec")
        assert "%" not in value.replace("%%", ""), "a lone % would be read as a field code"
        out.append(GLib.shell_parse_argv(value.replace("%%", "%"))[1])
    return out


