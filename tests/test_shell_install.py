def test_every_shipped_icon_is_installed_byte_for_byte(home):
    assert install(home).returncode == 0
    src = ROOT / "data/icons/hicolor"
    dst = home / ".local/share/icons/hicolor"
    shipped = [p.relative_to(src) for p in src.rglob("*") if p.is_file()]
    assert len(shipped) > 10
    for rel in shipped:
        assert (dst / rel).read_bytes() == (src / rel).read_bytes(), rel
    # the tray uses these three by name
    for n in ("idle", "streaming", "error"):
        assert (dst / f"scalable/status/airlinx-{n}-symbolic.svg").exists()


def test_reinstall_is_idempotent_and_replaces_stale_app_files(home):
    assert install(home).returncode == 0
    stale = home / ".local/share/airlinx/app/airlinx/removed_module.py"
    stale.write_text("x = 1\n")
    before = files(home)
    r = install(home)
    assert r.returncode == 0, r.stderr
    assert not stale.exists(), "app/ is rebuilt from scratch on update"
    after = files(home)
    assert set(before) - set(after) == {str(stale.relative_to(home))}
    assert {k: v for k, v in after.items()} == {k: v for k, v in before.items() if k in after}


