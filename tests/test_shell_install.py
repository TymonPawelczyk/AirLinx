def plant_unrelated_files(home):
    """Things a real home has that uninstall must never touch."""
    planted = {
        ".local/bin/other-tool": "#!/bin/sh\n",
        ".local/bin/airlinx-helper": "not ours despite the prefix\n",
        ".local/share/applications/other.desktop": "[Desktop Entry]\nName=Other\n",
        f".local/share/applications/{APP_ID}.other.desktop": "[Desktop Entry]\nName=Sibling\n",
        ".local/share/icons/hicolor/scalable/apps/other.svg": "<svg/>",
        ".local/share/icons/hicolor/scalable/status/airlinx-other-symbolic.svg": "<svg/>",
        ".local/share/icons/hicolor/48x48/apps/airlinx-extra.png": "png",
        ".local/share/airlinx-data/keep.txt": "sibling dir that only shares a prefix",
        ".config/autostart/other.desktop": "[Desktop Entry]\nName=Other\n",
        ".config/airlinx/settings.json": '{"version": 2}\n',
        ".config/airlinx/known_tvs.json": "{}\n",
        "Documents/notes.txt": "hello\n",
    }
    for rel, content in planted.items():
        p = home / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
    return planted


def test_uninstall_removes_everything_it_installed(home):
    assert install(home, "--autostart").returncode == 0
    assert install(home).returncode == 0                       # reinstall without --autostart keeps the old autostart
    r = run(home, "--uninstall")
    assert r.returncode == 0, r.stderr
    assert "odinstalowany" in r.stdout
    assert files(home) == {}, f"leftovers: {sorted(files(home))}"


def test_uninstall_touches_nothing_outside_its_own_paths(home):
    planted = plant_unrelated_files(home)
    before = files(home)
    assert install(home, "--autostart").returncode == 0
    assert run(home, "--uninstall").returncode == 0
    after = files(home)
    assert after == before
    for rel, content in planted.items():
        assert (home / rel).read_text() == content


def test_uninstall_keeps_user_settings_and_says_so(home):
    plant_unrelated_files(home)
    assert install(home).returncode == 0
    r = run(home, "--uninstall")
    assert "Ustawienia zostały" in r.stdout and ".config/airlinx" in r.stdout
    assert (home / ".config/airlinx/settings.json").read_text() == '{"version": 2}\n'
    assert (home / ".config/airlinx/known_tvs.json").exists(), "pinned TV identities survive an uninstall"


