def test_launcher_runs_the_installed_copy(home, tmp_path):
    """The generated launcher is valid bash and execs `python -m airlinx` from the installed tree."""
    fake_py = tmp_path / "fakepy"
    fake_py.write_text('#!/usr/bin/env bash\necho "cwd=$PWD"; echo "pp=$PYTHONPATH"; echo "args=$*"\n')
    fake_py.chmod(0o755)
    assert install(home, AIRLINX_PYTHON=str(fake_py)).returncode == 0
    out = subprocess.run([str(home / ".local/bin/airlinx"), "--debug", "--no-window"], capture_output=True, text=True,
                         env={"PATH": os.environ["PATH"], "HOME": str(home), "PYTHONPATH": "/preexisting"})
    app = home / ".local/share/airlinx/app"
    assert out.returncode == 0, out.stderr
    assert f"cwd={app}" in out.stdout
    assert f"pp={app}:/preexisting" in out.stdout            # existing PYTHONPATH is kept, ours goes first
    assert "args=-m airlinx --debug --no-window" in out.stdout


def test_honours_xdg_data_and_config_home(home, tmp_path):
    data, conf = tmp_path / "xdata", tmp_path / "xconf"
    r = install(home, "--autostart", XDG_DATA_HOME=str(data), XDG_CONFIG_HOME=str(conf))
    assert r.returncode == 0, r.stderr
    assert (data / "airlinx/app/airlinx/controller.py").exists()
    assert (data / f"applications/{APP_ID}.desktop").exists()
    assert (conf / f"autostart/{APP_ID}.desktop").exists()
    assert (data / "icons/hicolor/scalable/status/airlinx-idle-symbolic.svg").exists()
