def test_install_creates_launcher_desktop_icons_and_app_copy(home):
    r = install(home)
    assert r.returncode == 0, r.stderr
    assert "AirLinx zainstalowany" in r.stdout

    prefix = home / ".local/share/airlinx"
    launcher = home / ".local/bin/airlinx"
    assert launcher.is_file() and launcher.stat().st_mode & stat.S_IXUSR
    body = launcher.read_text()
    assert body.startswith("#!/usr/bin/env bash")
    assert f'PYTHONPATH="{prefix}/app' in body and f'cd "{prefix}/app"' in body
    assert f'exec "{sys.executable}" -m airlinx' in body
    # the test passes AIRLINX_PYTHON=sys.executable, which may itself live in the repo's .venv
    assert str(ROOT) not in body.replace(sys.executable, ""), "launcher must not depend on the repo checkout"

    app = prefix / "app"
    assert (app / "airlinx/controller.py").exists() and (app / "ui/index.html").exists()
    assert (app / "data").is_dir()
    assert not list(app.rglob("__pycache__")), "caches are not shipped"
    # the checkout's tests, docs, site and spikes are not copied
    assert not any((app / d).exists() for d in ("tests", "docs", "site", "spikes", ".git"))

    desktop = (home / f".local/share/applications/{APP_ID}.desktop").read_text()
    assert "@EXEC@" not in desktop
    assert f'Exec="{launcher}"\n' in desktop
    assert f'Exec="{launcher}" --no-window\n' in desktop      # the "run in tray" action
    assert "Icon=airlinx" in desktop and "StartupWMClass=airlinx" in desktop
    # no autostart unless asked
    assert not (home / f".config/autostart/{APP_ID}.desktop").exists()


def test_installed_desktop_files_are_valid(home):
    if shutil.which("desktop-file-validate") is None:
        pytest.skip("desktop-file-validate not installed")
    assert install(home, "--autostart").returncode == 0
    for p in (home / f".local/share/applications/{APP_ID}.desktop", home / f".config/autostart/{APP_ID}.desktop"):
        r = subprocess.run(["desktop-file-validate", str(p)], capture_output=True, text=True)
        out = r.stdout + r.stderr                 # "hint:" lines (menu categories) are advice, not defects
        assert r.returncode == 0 and "error:" not in out and "warning:" not in out, f"{p.name}: {out}"


