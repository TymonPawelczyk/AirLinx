def test_uninstall_does_not_follow_symlinks_out_of_home(home, tmp_path):
    """A symlinked icon dir or launcher must be unlinked, never its target emptied."""
    outside = tmp_path / "outside"
    outside.mkdir()
    (outside / "precious.txt").write_text("keep")
    assert install(home).returncode == 0
    launcher = home / ".local/bin/airlinx"
    launcher.unlink()
    launcher.symlink_to(outside / "precious.txt")
    assert run(home, "--uninstall").returncode == 0
    assert not launcher.exists() and not launcher.is_symlink()
    assert (outside / "precious.txt").read_text() == "keep"


